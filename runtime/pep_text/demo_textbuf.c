// Agent-4 demo: a real standalone native program built only on the
// pep_textbuf builder. It constructs a small but complete strict-C23 source
// file (shaped like Pep emitter output: checked arithmetic helpers plus a
// main) and writes it to stdout. No string literals bypass the builder:
// every byte of output passes through append calls, including integers
// formatted by pep_textbuf_append_i64.
#include <stdio.h>

#include "pep_textbuf.h"

static int emit(pep_textbuf_t *out)
{
    // Prologue: generated-file marker plus the includes an emitter needs.
    if (pep_textbuf_append_cstr(out, "/* Generated by the Agent-4 textbuf demo. */\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "#include <stdint.h>\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "#include <stdio.h>\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "\n") != 0) {
        return out->err;
    }
    // One checked helper, the same shape the Pep C23 emitter produces.
    if (pep_textbuf_append_cstr(out, "static int64_t demo_add(int64_t a, int64_t b)\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "{\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "  return a + b;\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "}\n\n") != 0) {
        return out->err;
    }
    // Main prints a computed constant: 6 + 7, formatted by the builder.
    if (pep_textbuf_append_cstr(out, "int main(void)\n{\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "  int64_t answer = demo_add(") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_i64(out, 6) != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, ", ") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_i64(out, 7) != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, ");\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "  (void)printf(\"%lld\\n\", (long long)answer);\n") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, "  return 0;\n}\n") != 0) {
        return out->err;
    }
    // Edge report: the two magnitudes the Pep int_width model pins.
    if (pep_textbuf_append_cstr(out, "/* i64min=") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_i64(out, (-9223372036854775807LL - 1)) != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, " i64max=") != 0) {
        return out->err;
    }
    if (pep_textbuf_append_i64(out, 9223372036854775807LL) != 0) {
        return out->err;
    }
    if (pep_textbuf_append_cstr(out, " */\n") != 0) {
        return out->err;
    }
    return PEP_TEXTBUF_OK;
}

int main(void)
{
    pep_textbuf_t out;
    // Join-path check: the same fragment list the emitter hands Python as
    // sourceParts, assembled here by the native join instead of "".join.
    static const char *const banner[] = {
        "/* fragments: ",
        "one",
        ", ",
        "two",
        " */\n"
    };
    if (pep_textbuf_init(&out) != PEP_TEXTBUF_OK) {
        return 1;
    }
    if (pep_textbuf_join(&out, banner, sizeof banner / sizeof banner[0]) != PEP_TEXTBUF_OK) {
        pep_textbuf_free(&out);
        return 1;
    }
    if (emit(&out) != PEP_TEXTBUF_OK) {
        pep_textbuf_free(&out);
        return 1;
    }
    // Overflow probe: an impossible reservation must fail cleanly and leave
    // the assembled bytes intact for the write below.
    if (pep_textbuf_reserve(&out, (size_t)-1) != PEP_TEXTBUF_OVERFLOW) {
        pep_textbuf_free(&out);
        return 1;
    }
    out.err = PEP_TEXTBUF_OK; // probe only; the bytes were never disturbed
    if (pep_textbuf_write(&out, stdout) != PEP_TEXTBUF_OK) {
        pep_textbuf_free(&out);
        return 1;
    }
    pep_textbuf_free(&out);
    return 0;
}
